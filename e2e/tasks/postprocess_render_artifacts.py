#!/usr/bin/env python3
"""Create comparison artifacts after a core white-model run.

This script is deliberately outside the Claude session.  It reads the batch log,
uses the same task image for ffmpeg/ffprobe, and writes only each item's managed
results directory.  Existing artifacts are preserved, so it is safe to resume.

Usage:
  python3 e2e/tasks/postprocess_render_artifacts.py --batch-log BATCH_LOG \
      --image IMAGE [--force]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shlex
import subprocess
import tempfile
from pathlib import Path


def sha256(path: Path) -> str | None:
    if not path.is_file():
        return None
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def docker_run(image: str, results: Path, reference: Path, command: list[str], timeout: int = 3600) -> subprocess.CompletedProcess:
    # Use argv through bash -lc only for the fixed ffmpeg pipeline below; paths
    # are shell-quoted and never supplied by the model.
    script = " ".join(shlex.quote(x) for x in command)
    return subprocess.run([
        "docker", "run", "--rm", "--network", "none",
        "-v", f"{results.resolve()}:/out:rw",
        "-v", f"{reference.resolve()}:/ref/source.mp4:ro",
        image, "bash", "-lc", script,
    ], capture_output=True, text=True, timeout=timeout)


def one(item: dict, image: str, force: bool) -> dict:
    item_id = item["id"]
    root = Path(item["item_root"])
    results = root / "results" / item_id
    ref = Path(item.get("video", ""))
    report = {"id": item_id, "reference": str(ref), "image": image,
              "whitebox_sha256": sha256(results / "whitebox.mp4")}
    if not ref.is_file() or not (results / "whitebox.mp4").is_file():
        report["status"] = "skipped_missing_reference_or_whitebox"
        return report
    if force or not (results / "compare.mp4").is_file():
        # Scale reference to the whitebox dimensions and hstack for the whole clip.
        cmd = ["ffmpeg", "-y", "-i", "/ref/source.mp4", "-i", "/out/whitebox.mp4",
               "-filter_complex", "[0:v][1:v]scale2ref=w=iw:h=ih[ref][wb];[ref][wb]hstack=inputs=2[v]",
               "-map", "[v]", "-an", "-c:v", "libx264", "-pix_fmt", "yuv420p", "/out/compare.mp4"]
        r = docker_run(image, results, ref, cmd)
        if r.returncode:
            report["compare_error"] = (r.stderr or r.stdout)[-2000:]
    if force or not (results / "compare.jpg").is_file():
        cmd = ["ffmpeg", "-y", "-sseof", "-1", "-i", "/out/compare.mp4",
               "-frames:v", "1", "-q:v", "2", "/out/compare.jpg"]
        r = docker_run(image, results, ref, cmd, timeout=300)
        if r.returncode:
            report["jpg_error"] = (r.stderr or r.stdout)[-2000:]
    if force or not (results / "README.md").is_file():
        (results / "README.md").write_text(
            f"# media2threejs result: {item_id}\n\n"
            "The white-model render was produced by the Claude Code session. "
            "This comparison file and report were generated by post-processing.\n\n"
            f"Reference: `{ref}`\nWhitebox: `whitebox.mp4`\n",
            encoding="utf-8")
    report["artifacts"] = {n: {"bytes": (results / n).stat().st_size if (results / n).is_file() else None,
                               "sha256": sha256(results / n)}
                          for n in ("whitebox.mp4", "compare.mp4", "compare.jpg", "README.md")}
    report["status"] = "ok" if all(v["bytes"] for v in report["artifacts"].values()) else "incomplete"
    (results / "postprocess_report.json").write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    return report


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--batch-log", required=True, type=Path)
    ap.add_argument("--image", required=True)
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()
    rows = [json.loads(line) for line in args.batch_log.read_text(encoding="utf-8").splitlines() if line.strip()]
    out = []
    for row in rows:
        if row.get("status") not in {"success", "no_video", "resume"}:
            continue
        # run_tasks records item_root only in the filesystem, derive it from batch log's
        # model output layout when the optional field is absent.
        if not row.get("item_root"):
            model_out = args.batch_log.parent
            row["item_root"] = str(model_out / "items" / row["id"])
        out.append(one(row, args.image, args.force))
    print(json.dumps(out, ensure_ascii=False, indent=2))
    return 0 if all(r.get("status") in {"ok", "skipped_missing_reference_or_whitebox"} for r in out) else 1


if __name__ == "__main__":
    raise SystemExit(main())
